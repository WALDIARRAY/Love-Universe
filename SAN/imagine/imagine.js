/* =========================================
   2. GET HTML ELEMENTS
========================================= */

const chapterContainer = document.getElementById("chapters");

const overlay = document.getElementById("overlay");

const explored = new Set();

let moments = [];
let active = 0;


/* =========================================
   3. CREATE ALL CHAPTERS AND CARDS
========================================= */

chapters.forEach((chapter, chapterIndex) => {

    const section = document.createElement("section");

    section.className = "chapter";


    const heading = document.createElement("div");

    heading.className = "chapter-head";

    heading.innerHTML = `
        <div>
            <p>${chapter.sub}</p>
            <h3>${chapter.icon} ${chapter.title}</h3>
        </div>

        <small>CHAPTER 0${chapterIndex + 1}</small>
    `;


    const grid = document.createElement("div");

    grid.className = "grid";


    chapter.moments.forEach((moment) => {

        const index = moments.length;


        // Store moment information

        moments.push({

            title: moment[0],

            icon: moment[1],

            description: moment[2],

            choice: moment[3],

            chapter: chapter.title

        });


        // Create card

        const card = document.createElement("button");

        card.className = "card";

        card.innerHTML = `

            <div class="art">
                ${moment[1]}
            </div>

            <div class="card-info">

                <div class="card-top">

                    <span>
                        MOMENT ${String(index + 1).padStart(2, "0")}
                    </span>

                    <span class="check"></span>

                </div>

                <h4>${moment[0]}</h4>

                <p>Open this little daydream ↗</p>

            </div>

        `;


        // Open popup when clicked

        card.addEventListener("click", () => {

            openMoment(index);

        });


        grid.appendChild(card);

    });


    section.append(heading, grid);

    chapterContainer.appendChild(section);

});


/* =========================================
   4. UPDATE PROGRESS BAR
========================================= */

function updateProgress() {

    const count = explored.size;

    const percentage = Math.round(
        (count / moments.length) * 100
    );


    document.getElementById("progressText").textContent =
        `${count} of ${moments.length} moments explored`;


    document.getElementById("percent").textContent =
        percentage + "%";


    document.getElementById("bar").style.width =
        percentage + "%";


    // Show heart on explored cards

    document.querySelectorAll(".card").forEach((card, index) => {

        const check = card.querySelector(".check");

        check.textContent = explored.has(index) ? "♥" : "";

    });


    // Show final message after all 30 moments

    if (count === moments.length) {

        document.getElementById("ending").classList.remove("hidden");

    }

}


/* =========================================
   5. OPEN A MOMENT
========================================= */

function openMoment(index) {

    active = index;

    const moment = moments[index];


    // Mark as explored

    explored.add(index);


    // Display moment information

    document.getElementById("sceneArt").textContent =
        moment.icon;


    document.getElementById("chapterName").textContent =
        moment.chapter.toUpperCase();


    document.getElementById("momentNumber").textContent =
        `MOMENT ${String(index + 1).padStart(2, "0")} / ${moments.length}`;


    document.getElementById("momentTitle").textContent =
        moment.title;


    document.getElementById("description").textContent =
        moment.description;


    // Display choices if this moment has them

    displayChoices(moment);


    // Previous button

    const previousButton = document.getElementById("previous");

    previousButton.disabled = index === 0;

    previousButton.style.opacity =
        index === 0 ? "0.35" : "1";


    // Next button

    const nextButton = document.getElementById("next");

    nextButton.textContent =
        index === moments.length - 1
            ? "FINISH THE DAYDREAM ↗"
            : "NEXT MOMENT →";


    // Show popup

    overlay.classList.remove("hidden");

    document.body.style.overflow = "hidden";


    updateProgress();

}


/* =========================================
   6. DISPLAY INTERACTIVE CHOICES
========================================= */

function displayChoices(moment) {

    const choiceBox = document.getElementById("choiceBox");

    const optionsContainer = document.getElementById("options");

    const reply = document.getElementById("reply");


    // Clear old choices

    optionsContainer.innerHTML = "";

    reply.classList.add("hidden");

    reply.textContent = "";


    // No choices for this moment

    if (!moment.choice) {

        choiceBox.classList.add("hidden");

        return;

    }


    // Show choice section

    choiceBox.classList.remove("hidden");


    document.getElementById("question").textContent =
        moment.choice.q;


    // Create choice buttons

    moment.choice.o.forEach((option, index) => {

        const button = document.createElement("button");

        button.textContent = option;


        button.addEventListener("click", () => {

            // Remove previous selection

            optionsContainer.querySelectorAll("button").forEach((item) => {

                item.classList.remove("selected");

            });


            // Highlight selected choice

            button.classList.add("selected");


            // Show response

            reply.textContent =
                moment.choice.r[index];

            reply.classList.remove("hidden");

        });


        optionsContainer.appendChild(button);

    });

}


/* =========================================
   7. CLOSE MOMENT POPUP
========================================= */

function closeMoment() {

    overlay.classList.add("hidden");

    document.body.style.overflow = "";

}


document.getElementById("close").addEventListener("click", closeMoment);


overlay.addEventListener("click", (event) => {

    if (event.target === overlay) {

        closeMoment();

    }

});


document.addEventListener("keydown", (event) => {

    if (event.key === "Escape") {

        closeMoment();

    }

});


/* =========================================
   8. BEGIN THE DAYDREAM
========================================= */

document.getElementById("begin").addEventListener("click", () => {

    const journey = document.getElementById("journey");

    journey.classList.remove("hidden");

    journey.scrollIntoView({

        behavior: "smooth"

    });

});


/* =========================================
   9. PREVIOUS MOMENT
========================================= */

document.getElementById("previous").addEventListener("click", () => {

    if (active > 0) {

        openMoment(active - 1);

    }

});


/* =========================================
   10. NEXT MOMENT
========================================= */

document.getElementById("next").addEventListener("click", () => {

    if (active < moments.length - 1) {

        openMoment(active + 1);

    } else {

        closeMoment();

        document.getElementById("ending").scrollIntoView({

            behavior: "smooth"

        });

    }

});


/* =========================================
   11. REPLAY THE EXPERIENCE
========================================= */

document.getElementById("replay").addEventListener("click", () => {

    // Reset explored moments

    explored.clear();


    // Reset progress

    updateProgress();


    // Hide final message

    document.getElementById("ending").classList.add("hidden");


    // Return to chapters

    document.getElementById("journey").scrollIntoView({

        behavior: "smooth"

    });

});
